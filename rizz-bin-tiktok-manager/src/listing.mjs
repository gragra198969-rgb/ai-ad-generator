import {createHash} from 'node:crypto';

// Physical-product facts need specific supporting evidence; do not infer them from images or marketing copy.
export const REQUIRED_SPECS = ['materials', 'dimensions', 'packageContents'];
export const OPTIONAL_SPECS = ['careInstructions', 'weight', 'compatibility', 'countryOfOrigin', 'safetyWarnings'];

function text(value) {
  return typeof value === 'string' ? value.replace(/\s+/g, ' ').trim() : '';
}

function verifiedSpec(entry) {
  if (!entry || typeof entry !== 'object' || Array.isArray(entry)) return null;
  const value = text(entry.value);
  const source = text(entry.source);
  // Requires specific traceable evidence. Human approval still verifies its authenticity.
  return value && source.length >= 8 && !/^(unknown|n\/a|tbd|none)$/i.test(value) ? {value, source} : null;
}

export function buildListingPreview(product, listingDetails = {}) {
  if (!product?.id) throw Error('Product not found');
  const issues = [];
  const title = text(product.title);
  const description = typeof product.description === 'string' ? product.description.trim() : '';
  if (!title) issues.push('Shopify product title missing');
  if (title.length > 120) issues.push('Title exceeds 120-character review limit');
  if (description.length < 50) issues.push('Shopify description missing or too short; verify real features and benefits');
  if (!product.featuredImage?.url?.startsWith('https://')) issues.push('Authentic featured product image missing');

  const specs = {};
  for (const key of [...REQUIRED_SPECS, ...OPTIONAL_SPECS]) {
    const entry = verifiedSpec(listingDetails.specs?.[key]);
    if (entry) specs[key] = entry;
    else if (REQUIRED_SPECS.includes(key)) issues.push('Verified ' + key + ' missing (include value and evidence source)');
    else if (listingDetails.specs?.[key] != null) issues.push(key + ': invalid or unsupported evidence');
  }
  if (!text(listingDetails.categoryId)) issues.push('TikTok category ID not verified');
  if (!text(listingDetails.categoryEvidence) || text(listingDetails.categoryEvidence).length < 8) issues.push('TikTok category evidence missing');
  const variants = (product.variants?.nodes || []).map(v => ({
    id: v.id,
    title: text(v.title),
    sku: text(v.sku) || null,
    priceUsd: String(v.price),
    optionValues: (v.selectedOptions || []).filter(x => x.name && x.value && x.name !== 'Title').map(x => ({name:text(x.name),value:text(x.value)}))
  }));
  if (!variants.length) issues.push('No Shopify variants');
  if (product.variants?.pageInfo?.hasNextPage) issues.push('Truncated variants - cannot approve partial catalog');
  if (variants.some(v => !v.sku)) issues.push('At least one variant is missing its supplier SKU');
  const photos = [...new Set([
    product.featuredImage?.url,
    ...(product.media?.nodes || []).map(m => m?.image?.url)
  ].filter(url => typeof url === 'string' && url.startsWith('https://')))];
  if (!photos.length) issues.push('No authentic product photo to show');
  if (product.media?.pageInfo?.hasNextPage) issues.push('Product media list truncated; review full gallery');

  // Preview only. The Shopify-TikTok channel syncs the real Shopify listing; this never edits product data.
  const listing = {
    shopifyProductId: product.id,
    title, description,
    vendor: text(product.vendor),
    productType: text(product.productType),
    categoryId: text(listingDetails.categoryId) || null,
    specs, variants, photos
  };
  const fingerprint = createHash('sha256').update(JSON.stringify(listing)).digest('hex');
  return {listing, fingerprint, issues, readyForOwnerReview: issues.length === 0, autoGeneratedClaims: false};
}

export function assessListingReview(preview, approval) {
  const issues = [...preview.issues];
  if (approval?.listingReview?.approved !== true) issues.push('Owner has not approved listing title, description, specs, variants and photos');
  if (approval?.listingReview?.fingerprint !== preview.fingerprint) issues.push('Listing approval fingerprint missing or stale; review the updated preview');
  return {eligible: issues.length === 0, issues};
}
